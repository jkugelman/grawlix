// Searches OR-filter thresholds (letters hd·miss | phones hd·miss) for the
// fewest survivors with no false rejections, per cutoff, calibrating on
// half the ground-truth queries and checking on the other half.
//   node filter/calib.mjs truth.json ../../site/src/engine/twins-thresholds.js  fit and write the table
//   node filter/calib.mjs truth.json - half.json              check half-fit thresholds on the other half
import fs from 'node:fs';
import path from 'node:path';
import { loadAll } from '../readings.mjs';
import { letterSig, phoneSigs, letterPair, phonePair } from './feats.mjs';

const truth = JSON.parse(fs.readFileSync(process.argv[2]));
const C = loadAll(40);
const LS = C.entries.map(letterSig), PS = C.entries.map(phoneSigs);
const idx = new Map(C.entries.map((e, i) => [e.norm, i]));
const hash = (s) => [...s].reduce((h, c) => (h * 31 + c.charCodeAt(0)) >>> 0, 7);

const feat = (ls, ps, i) => {
  const lp = letterPair(ls, LS[i]), pp = phonePair(ps, PS[i]);
  return [lp.hd / lp.L, lp.miss / lp.L, pp ? pp.hd : Infinity, pp ? pp.miss : Infinity];
};
const hits = [];
const texts = Object.keys(truth);
for (const text of texts) {
  const q = C.asEntry(text), ls = letterSig(q), ps = phoneSigs(q), calib = hash(text) % 2 === 0;
  for (const [norm, loose, route] of truth[text].hits) {
    if (route === 'R' || route === 'U' || route === 'W') continue; // query() adds these past the filter
    const i = idx.get(norm);
    if (i !== undefined) hits.push({ text, norm, loose, route, calib, f: feat(ls, ps, i) });
  }
}
const sample = [];
for (const text of texts.filter((_, k) => k % 20 === 0)) {
  const q = C.asEntry(text), ls = letterSig(q), ps = phoneSigs(q);
  for (let i = 0; i < LS.length; i += 7) sample.push(feat(ls, ps, i));
}
console.log(`${hits.length} hits, ${sample.length} sampled pairs`);

const passes = (f, [a, b, c, d]) => (f[0] <= a && f[1] <= b) || (f[2] <= c && f[3] <= d);
const grid = (lo, hi, st) => { const g = []; for (let x = lo; x <= hi + 1e-9; x += st) g.push(+x.toFixed(3)); return g; };
function fit(hs) {
  let best = null;
  for (const a of grid(0.3, 2, 0.1)) for (const b of grid(0.3, 2, 0.1)) {
    const left = hs.filter((h) => !(h.f[0] <= a && h.f[1] <= b));
    if (left.some((h) => h.f[2] === Infinity)) continue;
    for (const c of grid(0, 2.5, 0.1)) {
      if (left.some((h) => h.f[2] > c)) continue;
      const th = [a, b, c, Math.ceil(100 * Math.max(0, ...left.map((h) => h.f[3]))) / 100];
      let n = 0;
      for (const f of sample) if (passes(f, th)) n++;
      if (!best || n < best.n) best = { th, n };
    }
  }
  return best.th;
}
const surv = (th) => (100 * sample.filter((f) => passes(f, th)).length / sample.length).toFixed(1) + '%';
// Monotone in the cutoff, so a near-boundary pair any looser cutoff keeps
// survives here too, plus a flat margin for pairs the truth never saw.
const MARGIN = 0.15;
const widen = (table, m) => {
  const out = {}, run = [0, 0, 0, 0];
  for (const c of Object.keys(table).map(Number).sort((a, b) => a - b)) {
    table[c].forEach((x, k) => (run[k] = Math.max(run[k], x)));
    out[c] = run.map((x) => +(x + m).toFixed(3));
  }
  return out;
};
if (process.argv[4]) {
  const half = JSON.parse(fs.readFileSync(process.argv[4]));
  for (const m of [0, 0.05, 0.1, 0.15]) {
    const t = widen(half, m);
    console.log(`margin ${m}: ` + Object.entries(t).map(([c, th]) => {
      const test = hits.filter((h) => h.loose <= +c && !h.calib);
      const lost = test.filter((h) => !passes(h.f, th));
      return `${c} lost ${lost.length} surv ${surv(th)}`;
    }).join(' | '));
  }
  process.exit(0);
}
const CUTS = [0.1, 0.15, 0.2, 0.25, 0.3, 0.35, 0.4, 0.45];
const table = {};
for (const cut of CUTS) {
  const under = hits.filter((h) => h.loose <= cut);
  const cal = under.filter((h) => h.calib), test = under.filter((h) => !h.calib);
  const th = fit(cal);
  const line = [0, 0.05, 0.1, 0.15].map((m) => {
    const t = th.map((x) => x + m);
    return `+${m}: lost ${test.filter((h) => !passes(h.f, t)).length}/${test.length} surv ${surv(t)}`;
  });
  table[cut] = fit(under);
  console.log(`cut ${cut}: half-fit ${th.join(' ')} | ${line.join(' | ')} | full-fit ${table[cut].join(' ')}`);
}
fs.writeFileSync(process.argv[3], `// Generated by calib.mjs from ${path.basename(process.argv[2])}: [letter hd/L, letter miss/L, phone hd/L, phone miss/L] per cutoff.
export const THRESHOLDS = ${JSON.stringify(widen(table, MARGIN))};
`);
