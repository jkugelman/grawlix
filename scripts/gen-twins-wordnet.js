// Generates site/data/twins-wordnet.txt, the meaning links Twins
// uses to call a pair related (site/src/engine/twins-wordnet.js), from
// Open English WordNet 2025 (CC BY 4.0; see scripts/wordnet.js).
//   node scripts/gen-twins-wordnet.js
//
// Each lemma line is `lemma pos key…`: pos is the parts of speech it has
// (n v a r), and two lemmas are related when their keys overlap. A lemma's
// keys are its synsets, itself, and the lemmas it links to by derivation,
// pertainym, participle or attribute pointers, so the overlap test covers a
// shared synset, a direct link and a link through one shared neighbor.
// Hypernym and sister links are left out: they tie unrelated words
// (TIME~FITS, SLIP~SKIP). Exception lines `=inflected base…` follow.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { fetchWordNet } from './wordnet.js';

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '../site/data/twins-wordnet.txt');
const POS = { noun: 'n', verb: 'v', adj: 'a', adv: 'r' };
const LEX = new Set(['+', '\\', '<', '=']);

const files = await fetchWordNet(Object.keys(POS).flatMap(f => [`data.${f}`, `${f}.exc`]));
const add = (m, k, v) => { let s = m.get(k); if (!s) m.set(k, (s = new Set())); s.add(v); };
const senses = new Map(), links = new Map(), words = new Map(), pos = new Map(), exc = new Map();
const parsed = [];
for (const [file, p] of Object.entries(POS)) {
  for (const l of files[`${file}.exc`].split('\n')) {
    const [infl, ...bases] = l.trim().split(' ');
    if (infl && bases.length) for (const b of bases) add(exc, infl, b);
  }
  for (const l of files[`data.${file}`].split('\n')) {
    if (!l || l.startsWith(' ')) continue;
    const f = l.split(' | ')[0].split(' ');
    const id = f[0] + (f[2] === 's' ? 'a' : f[2]);
    const n = parseInt(f[3], 16), ws = [];
    for (let i = 0; i < n; i++) ws.push(f[4 + 2 * i].replace(/\(.*\)$/, '').toLowerCase());
    words.set(id, ws);
    for (const w of ws) { add(senses, w, id); add(pos, w, id.slice(-1)); }
    let k = 4 + 2 * n;
    const pc = +f[k++], ptrs = [];
    for (let i = 0; i < pc; i++, k += 4) {
      const [sym, off, ps, st] = f.slice(k, k + 4);
      if (LEX.has(sym)) ptrs.push({ to: off + (ps === 's' ? 'a' : ps), src: parseInt(st.slice(0, 2), 16), tgt: parseInt(st.slice(2), 16) });
    }
    parsed.push({ ws, ptrs });
  }
}
for (const { ws, ptrs } of parsed) {
  for (const { to, src, tgt } of ptrs) {
    const tw = words.get(to);
    if (!tw) continue;
    const from = src ? [ws[src - 1]] : ws, dest = tgt ? [tw[tgt - 1]] : tw;
    for (const a of from) for (const b of dest) if (a !== b) { add(links, a, b); add(links, b, a); }
  }
}

const lemmas = [...senses.keys()].sort();
const keysOf = new Map(lemmas.map(w => [w, [...senses.get(w), 'L' + w, ...[...(links.get(w) ?? [])].map(x => 'L' + x)]]));
const freq = new Map();
for (const ks of keysOf.values()) for (const k of ks) freq.set(k, (freq.get(k) ?? 0) + 1);
const ids = new Map([...freq.entries()].filter(([, c]) => c > 1).sort((a, b) => b[1] - a[1]).map(([k], i) => [k, i.toString(36)]));
const out = [
  '# Twins meaning links, generated by scripts/gen-twins-wordnet.js from Open English WordNet 2025',
  '# (https://en-word.net/), licensed CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/).',
];
for (const w of lemmas) {
  // A key no other lemma has can never overlap, so it is dropped.
  const ks = [...new Set(keysOf.get(w).map(k => ids.get(k)).filter(Boolean))];
  out.push(`${w} ${[...pos.get(w)].sort().join('')}${ks.length ? ' ' + ks.join(' ') : ''}`);
}
for (const [infl, bases] of [...exc.entries()].sort()) out.push(`=${infl} ${[...bases].join(' ')}`);
fs.writeFileSync(OUT, out.join('\n') + '\n');
console.log(`${lemmas.length} lemmas, ${exc.size} exceptions, ${(fs.statSync(OUT).size / 1e6).toFixed(1)} MB`);
