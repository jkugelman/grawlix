// Regenerates site/src/engine/space-out-bigrams-data.js: node scripts/gen-space-out-bigrams.js
// Sources: the JK and Nediger wordlists (both MIT).
import { writeFile } from 'node:fs/promises';
import { WORDLIST_PUBLISHERS } from '../site/src/core/constants.js';
import { toNorm } from '../site/src/engine/norm.js';

const OUT = new URL('../site/src/engine/space-out-bigrams-data.js', import.meta.url);
const SOURCES = ['jkugelman', 'nediger'];   // the spaced default lists; STWL/Broda ship bare
const MIN_COUNT = 5;   // a pair in fewer entries is coincidence, not signal — docs/design.md § Space out

const counts = new Map();
for (const id of SOURCES) {
  const pub = WORDLIST_PUBLISHERS.find(p => p.id === id);
  const res = await fetch(pub.url);
  if (!res.ok) throw new Error(`fetch ${pub.url}: ${res.status}`);
  const text = await res.text();
  let entries = 0, spaced = 0;
  for (const line of text.split('\n')) {
    const display = line.split(';')[0].trim();
    if (!display) continue;
    entries++;
    const words = display.split(/\s+/).map(toNorm).filter(Boolean);
    if (words.length < 2) continue;
    // Skip entries whose words don't reassemble to the norm: a hyphen/apostrophe dropped
    // by toNorm would pair fragments the segmenter never emits as parts (dead, but noise).
    if (words.join('') !== toNorm(display)) continue;
    spaced++;
    for (let i = 0; i < words.length - 1; i++) {
      const k = `${words[i]} ${words[i + 1]}`;
      counts.set(k, (counts.get(k) ?? 0) + 1);
    }
  }
  console.log(`${id}: ${entries} entries, ${spaced} clean multi-word`);
}

const rows = [...counts.entries()]
  .filter(([, c]) => c >= MIN_COUNT)
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))   // by key: stable diffs, tighter gzip
  .map(([k, c]) => `${k} ${c}`);

const header = `'use strict';

// Generated by scripts/gen-space-out-bigrams.js — do not edit by hand. Word-pair counts
// mined from the spaced entries of the JK and Nediger wordlists (both MIT), kept when a
// pair appears in ${MIN_COUNT}+ entries; the space-out segmenter re-ranks its splits toward
// them. Format: one \`word1 word2 count\` per line. See docs/design.md § Space out.

export const SPACE_OUT_BIGRAMS = \`
${rows.join('\n')}
\`;
`;
await writeFile(OUT, header);
console.log(`Wrote ${OUT.pathname}: ${rows.length} bigrams (prune ${MIN_COUNT})`);
